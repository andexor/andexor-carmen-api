"""Generate src/models.py: the fields of every stored record, and of every body the code accepts.

The fields of a record come from the database schema, which is the migrations in andexor-carmen-main
(found through CARMEN_MAIN, like run.sh). The fields of a body come from the field lists in
src/records.py, which are what the code checks a body against. Nobody writes these models by hand.
See specs/032-openapi-models/spec.md.

    python3 tools/gen_models.py           write src/models.py
    python3 tools/gen_models.py --check   fail when src/models.py is not what would be written
"""

import os
import pathlib
import re
import sqlite3
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / "src" / "models.py"
sys.path.insert(0, str(ROOT / "src"))

import records  # noqa: E402

# Columns that no answer of the API carries.
HIDDEN = {"document": {"r2_key"}, "srt": {"active"}, "enrichment_key": {"active"}, "ai_run": {"dossier"}, "ai_run_fact": {"ai_run_id"}}
SKIPPED = {"schema_migration"}
TYPES = {"TEXT": "str", "INTEGER": "int", "REAL": "float"}
BODY_TYPES: dict[type, str] = {str: "str", int: "int", float: "float", bool: "bool"}

HEADER = '''# SPDX-License-Identifier: Apache-2.0
# Copyright 2026 Andexor Network, Inc.
# Author: Ed Jenkins

"""The fields of every stored record and of every body the code accepts, for the OpenAPI specification.

GENERATED by tools/gen_models.py from the migrations in andexor-carmen-main and the field lists in
src/records.py. Do not edit: change the schema or the field list, then run the generator.
"""

from pydantic import BaseModel, ConfigDict, Field


class Row(BaseModel):
    """An answer names exactly these fields: one the specification does not know is an error."""

    model_config = ConfigDict(extra="forbid")
'''


def migrations() -> list[pathlib.Path]:
    folder = pathlib.Path(os.environ.get("CARMEN_MAIN", ROOT.parent / "andexor-carmen-main")) / "db" / "carmen"
    files = sorted(f for f in folder.glob("[0-9][0-9][0-9][0-9]_*.sql") if not f.name.endswith(".base.sql"))
    if not files:
        raise SystemExit(f"no migrations in {folder}: set CARMEN_MAIN to the checkout of andexor-carmen-main")
    return files


def database(files: list[pathlib.Path]) -> sqlite3.Connection:
    """The schema with no triggers: they are not needed here, and theirs need a newer SQLite than some Pythons have."""
    connection = sqlite3.connect(":memory:")
    for file in files:
        statement = ""
        for line in file.read_text().splitlines(keepends=True):
            statement += line
            if sqlite3.complete_statement(statement):
                if not re.match(r"(CREATE|DROP)\s+TRIGGER", re.sub(r"--[^\n]*", "", statement).strip(), re.IGNORECASE):
                    connection.execute(statement)
                statement = ""
    return connection


def srt_domains(files: list[pathlib.Path]) -> dict[tuple[str, str], str]:
    """(table, column) to the SRT domain named in the comment on the column's line."""
    found: dict[tuple[str, str], str] = {}
    for file in files:
        table = ""
        for line in file.read_text().splitlines():
            if match := re.match(r"\s*(?:CREATE TABLE|ALTER TABLE)\s+(\w+)", line, re.IGNORECASE):
                table = match.group(1)
            if match := re.search(r"--\s*SRT domain:\s*(\w+)", line):
                column = re.match(r"\s*(?:ALTER TABLE\s+\w+\s+ADD COLUMN\s+)?(\w+)", line, re.IGNORECASE)
                if column and table:
                    found[(table, column.group(1))] = match.group(1)
    return found


def class_name(table: str) -> str:
    return "".join(part.capitalize() for part in table.split("_"))


def about(column: str, domain: str | None, flag: bool) -> str:
    if domain:
        return f"A code of the SRT domain {domain}"
    if flag:
        return "0 or 1"
    if column.endswith("_date"):
        return "A date, YYYY-MM-DD"
    if column.endswith("_at"):
        return "A time in UTC, ISO 8601"
    return ""


def field(name: str, kind: str, optional: bool, text: str, default: bool) -> str:
    kind = f"{kind} | None" if optional else kind
    if text:
        return f"    {name}: {kind} = Field({'None, ' if default else ''}description={text!r})".replace("'", '"')
    return f"    {name}: {kind}" + (" = None" if default else "")


def generate() -> str:
    files = migrations()
    connection = database(files)
    domains = srt_domains(files)
    parts = [HEADER]
    tables = [row[0] for row in connection.execute("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name")]
    for table in tables:
        if table in SKIPPED or table.startswith("sqlite_"):
            continue
        sql = str(connection.execute("SELECT sql FROM sqlite_master WHERE name = ?", (table,)).fetchone()[0])
        lines = [f"\n\nclass {class_name(table)}(Row):", f'    """One row of the table {table}."""', ""]
        for _, name, declared, notnull, _, key in connection.execute(f"PRAGMA table_info({table})"):
            if name in HIDDEN.get(table, set()):
                continue
            flag = bool(re.search(rf"\b{name}\s+IN\s*\(\s*0\s*,\s*1\s*\)", sql))
            kind = TYPES.get(str(declared).upper(), "object")
            lines.append(field(name, kind, not (notnull or key), about(name, domains.get((table, name)), flag), False))
        parts.append("\n".join(lines) + "\n")
    for constant in sorted(vars(records)):
        if not constant.endswith("_FIELDS"):
            continue
        stem = constant.removesuffix("_FIELDS")
        codes: dict[str, str] = getattr(records, f"{stem}_CODES", {})
        lines = [f"\n\nclass {stem.capitalize()}Body(BaseModel):", f'    """The fields a body may set: records.{constant}. Which ones a route needs is checked by the code."""', ""]
        for name, kind in getattr(records, constant).items():
            lines.append(field(name, BODY_TYPES.get(kind, "object"), True, about(name, codes.get(name), False), True))
        parts.append("\n".join(lines) + "\n")
    return "".join(parts)


if __name__ == "__main__":
    text = generate()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text() != text:
            raise SystemExit("src/models.py is not what tools/gen_models.py writes: run python3 tools/gen_models.py")
        print("src/models.py matches the schema and the field lists")
    else:
        try:
            TARGET.write_text(text)
        except OSError as e:
            raise SystemExit(f"could not write {TARGET}: {e}") from e
        print(f"wrote {TARGET.relative_to(ROOT)}")
